import fs from 'node:fs';
const { chromium } = await import(process.env.CREATURE_PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({headless:true, executablePath:process.env.CREATURE_CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const output = 'docs/qa/creature-system/contrast-v2';
fs.mkdirSync(output, {recursive:true});
const errors = [], failures = [], results = [];
const check = (ok, message) => { if (!ok) throw new Error(message); };
try {
  for (const width of [1440, 390, 320]) {
    const page = await browser.newPage({viewport:{width, height:1100}});
    page.on('pageerror', error => errors.push(String(error)));
    page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
    await page.goto(process.env.CREATURE_PREVIEW_URL ?? 'http://127.0.0.1:5189/creature-system-lab.html');
    await page.getByRole('button', {name:'Art production', exact:true}).click();
    const clay = page.locator('.cs-clay-direction');
    check(await clay.locator('.cs-creature-card').count() === 3, 'Three clay cards in shared frame');
    for (const img of await clay.locator('.cs-clay-cards img').all()) await img.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('.cs-clay-cards img')].every(img => img.complete && img.naturalWidth > 0));
    check(await clay.locator('.cs-art-caption').allTextContents().then(texts => texts.every(text => text === 'Rounded clay image · review pending')), 'Image cards never claim a 3D model');
    const cardBox = await clay.locator('.cs-creature-card').first().boundingBox();
    check(Math.abs(cardBox.width / cardBox.height - 5 / 7) < .01, 'Clay card preserves 5:7');
    await clay.screenshot({path:`${output}/clay-cards-${width}.png`});
    await clay.getByRole('button', {name:'Try grounded Echo', exact:true}).click();
    check(await clay.locator('.cs-creature-card').nth(2).locator('img').getAttribute('src').then(src => src.includes('echo-grounded-alternative')), 'Echo alternative selectable');
    await clay.locator('.cs-creature-card').nth(2).click();
    check(await page.getByRole('dialog').locator('img').getAttribute('src').then(src => src.includes('echo-grounded-alternative')), 'Enlargement keeps selected clay variant');
    check(await page.getByRole('dialog').locator('canvas').count() === 0, 'Image preview does not launch mismatched 3D');
    await page.keyboard.press('Escape');
    check(await clay.locator('.cs-creature-card').nth(2).evaluate(element => element === document.activeElement), 'Clay card focus returns');
    await clay.getByRole('button', {name:'Keep airy Echo', exact:true}).click();
    check(await clay.locator('.cs-creature-card').nth(2).locator('img').getAttribute('src').then(src => src.endsWith('/echo-clay.png')), 'Liked Echo preserved');
    const review = page.locator('.cs-contrast-review');
    check(await review.getByRole('button', {name:'Original → rounded clay', exact:true}).getAttribute('aria-pressed') === 'true', 'Clay comparison is preferred by default');
    await review.getByRole('button', {name:'Before → new original', exact:true}).click();
    const loaded = async () => page.waitForFunction(() => [...document.querySelectorAll('.cs-contrast-pair img')].length === 6 && [...document.querySelectorAll('.cs-contrast-pair img')].every(img => img.complete && img.naturalWidth > 0));
    await loaded();
    check(await review.locator('article').count() === 3, 'Three family comparisons');
    check(await review.locator('img[src*="comparisons/mature-trio-v2"]').count() === 3, 'Original before/after retains previous candidates');
    await review.screenshot({path:`${output}/original-${width}.png`});
    await review.getByRole('button', {name:'Original → rounded clay', exact:true}).click();
    await loaded();
    check(await review.locator('img[src$="-clay.png"]').count() === 3, 'Three clay images');
    check(await review.locator('canvas').count() === 0, 'Clay image comparison does not substitute a fake model');
    check(await review.getByRole('status').innerText().then(text => text.includes('not rotatable 3D models')), 'Raster limitation visible');
    await review.screenshot({path:`${output}/clay-${width}.png`});
    const imageButton = review.getByRole('button', {name:'Enlarge Bloom Mite: Rounded clay image', exact:true});
    await imageButton.click();
    check(await page.getByRole('dialog').isVisible(), 'Image enlargement opens');
    check(await page.evaluate(() => document.body.style.overflow === 'hidden'), 'Dialog scroll lock');
    await page.keyboard.press('Escape');
    check(await page.getByRole('dialog').count() === 0, 'Escape closes image review');
    check(await imageButton.evaluate(element => element === document.activeElement), 'Focus returns to exact image');
    await review.getByLabel('Greyscale', {exact:true}).check();
    await review.getByLabel('96px test', {exact:true}).check();
    await review.getByLabel('Hide identity hints', {exact:true}).check();
    check(await review.locator('.cs-contrast-notes').count() === 0, 'Emotion and identity hints hidden');
    check(await review.getByRole('heading', {name:'Study A', exact:true}).isVisible(), 'Neutral study labels');
    check(await review.locator('img').evaluateAll(images => images.every(img => getComputedStyle(img).filter === 'grayscale(1)' && img.getBoundingClientRect().width <= 96)), 'Thumbnail and greyscale modes');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No horizontal overflow at ${width}`);
    await review.screenshot({path:`${output}/blind-${width}.png`});
    results.push({width, clayCards:true, correctRasterCaption:true, echoVariants:true, exactImageEnlargement:true, beforeAfter:true, clayImages:true, enlargedDialog:true, focusReturn:true, greyscale:true, thumbnail:true, hiddenHints:true, noOverflow:true});
    await page.close();
  }
  check(errors.length === 0 && failures.length === 0, JSON.stringify({errors, failures}));
  fs.writeFileSync(`${output}/report.json`, JSON.stringify({results, errors, failures}, null, 2));
  console.log(JSON.stringify({results, errors, failures}, null, 2));
} finally { await browser.close(); }
